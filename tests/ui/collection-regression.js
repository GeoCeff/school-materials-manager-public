async (page) => {
  const assert = (value,message) => { if (!value) throw new Error(message); };
  await page.getByRole('button',{name:'Collect',exact:true}).click();
  await page.getByRole('heading',{name:'Collect school materials'}).waitFor();
  await page.getByRole('button',{name:'Continue to connection',exact:true}).click();
  await page.getByRole('button',{name:'Continue to courses',exact:true}).click();
  await page.getByRole('button',{name:'Choose files for review',exact:true}).click();
  await page.getByRole('heading',{name:'Organize',exact:true}).waitFor();
  await page.getByText('Local organization assistant',{exact:true}).click();
  await page.getByRole('button',{name:'Find local suggestions',exact:true}).click();
  await page.getByRole('checkbox',{name:'Use CMSC 123'}).check();
  await page.getByRole('button',{name:'Apply selected labels to draft',exact:true}).click();
  const draft=await page.evaluate(()=>window.archive.collection.status());
  assert(draft.plan.mappings[0].subject==='Unclassified','A suggestion was applied before confirmation');
  assert(await page.getByLabel('Subject / course',{exact:true}).inputValue()==='CMSC 123','Local label suggestion did not reach the draft');
  await page.getByLabel('Subject / course',{exact:true}).fill('CMSC 123');
  await page.getByLabel('Academic year',{exact:true}).fill('2026-2027');
  await page.getByLabel('Semester',{exact:true}).selectOption('First Semester');
  await page.getByRole('button',{name:'Save organization and review',exact:true}).click();
  await page.getByRole('region',{name:'Collection review',exact:true}).waitFor();
  const review = await page.evaluate(() => window.archive.collection.status());
  assert(review.plan.items.length === 2,'Expected the isolated native file selection');
  assert(review.plan.items[0].localPath === undefined,'Private source path exposed through the bridge');
  assert((await page.getByRole('region',{name:'Collection review',exact:true}).locator('small').allTextContents()).filter(text=>text.startsWith('CMSC 123 · File copy')).length===2,'Review did not show confirmed course labels');
  await page.getByText(/0000000000000000/).first().waitFor();
  await page.getByRole('button',{name:'Collect 2 selected resources',exact:true}).click();
  let done;
  for (let attempt=0;attempt<100;attempt++) { done=await page.evaluate(() => window.archive.collection.status()); if(done.job?.state==='completed') break; await page.waitForTimeout(100); }
  assert(done.job.published === 2 && done.job.failed === 0,`Files were not published: ${JSON.stringify(done.job)}`);
  let searchable = false;
  for(let attempt=0;attempt<100;attempt++) { searchable=await page.evaluate(async ()=>(await window.archive.search('collectionregression',{},0)).total===1);if(searchable)break;await page.waitForTimeout(100); }
  assert(searchable,'Completed collection did not reach the offline search index');
  const coverage=await page.evaluate(()=>window.archive.collection.coverage());
  assert(coverage.filter(item=>item.state==='searchable').length===1&&coverage.filter(item=>item.state==='unsupported').length===1,'Collection and search coverage were conflated');
  const denied = await page.evaluate(async () => { try { await window.archive.collection.start(['../../unapproved']); return false; } catch { return true; } });
  assert(denied,'Invalid selection was accepted');
  await page.getByRole('button',{name:'1 Source',exact:true}).click();
  await page.getByLabel('Source',{exact:true}).selectOption('uvec');
  assert(await page.getByRole('button',{name:/5\s*Review/}).isDisabled(),'Switching to UVEC reused the previous manual review');
  await page.getByRole('button',{name:'Continue to connection',exact:true}).click();
  assert(await page.getByRole('button',{name:'Check setup',exact:true}).count()===0,'Manual UVEC import incorrectly requires service setup');
  await page.getByRole('button',{name:'Continue to courses',exact:true}).click();
  assert(await page.getByRole('button',{name:'Choose files for review',exact:true}).isEnabled(),'UVEC without a token cannot select manual downloads');
  await page.getByRole('button',{name:'2 Connect',exact:true}).click();
  await page.getByText('Advanced: school-approved UVEC service',{exact:true}).click();
  await page.getByLabel('UVEC collection method').selectOption('automatic');
  await page.getByRole('button',{name:'Check setup',exact:true}).click();
  await page.getByText('School administrator request',{exact:true}).click();
  assert((await page.getByLabel('UVEC administrator request').inputValue()).includes('core_course_get_contents'),'Administrator request is missing');
  await page.getByRole('button',{name:'Choose restricted UVEC token JSON'}).click();
  await page.getByRole('alert').filter({hasText:'disabled in the synthetic demo'}).waitFor();
  await page.getByRole('button',{name:'1 Source',exact:true}).click();
  await page.getByLabel('Source',{exact:true}).selectOption('google');
  assert(await page.getByRole('button',{name:/5\s*Review/}).isDisabled(),'Switching to Google reused the previous source review');
  await page.getByRole('button',{name:'Continue to connection',exact:true}).click();
  await page.getByText('Advanced Google setup and permissions',{exact:true}).click();
  await page.getByRole('button',{name:'Choose Desktop client JSON',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'disabled in the synthetic demo'}).waitFor();
  await page.getByText('Privacy and support diagnostics',{exact:true}).click();
  await page.getByRole('button',{name:'Preview sanitized report',exact:true}).click();
  const report=await page.getByLabel('Sanitized support report').textContent();
  assert(!/CMSC|fixture|AppData|Lecture|\.txt|\.zip/.test(report),'Support report exposed private review metadata');
  await page.getByRole('button',{name:'Save previewed report',exact:true}).click();
  await page.getByRole('button',{name:'1 Source',exact:true}).click();
  await page.getByLabel('Source',{exact:true}).selectOption('manual');
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.getByRole('button',{name:'Collect',exact:true}).focus();
  await page.keyboard.press('Enter');
  await page.getByRole('heading',{name:'Collect school materials'}).waitFor();
  await page.keyboard.press('Escape');
  assert(await page.getByRole('button',{name:'Collect',exact:true}).evaluate(element => document.activeElement === element),'Dialog focus did not return to Collect');
  return {passed:true,published:done.job.published,autoIndexed:true,guidedFlow:true,confirmedLocalSuggestions:true,distinctSearchCoverage:true,adminRequest:true,sanitizedReport:true,reviewedSelection:true,privateSourceHidden:true,syntheticAccountGuards:true,keyboard:true};
}
